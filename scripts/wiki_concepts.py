def _escape_md_table_cell(text: str) -> str:
    """Escape characters that break a Markdown table row or a `[text](url)`
    link (issue #150 FIX4): a video title or a concept's `as_mentioned` /
    `branch` phrase is creator-authored text that can contain a literal
    `|` (splits the table row) or `[`/`]` (breaks the link's text span).
    """
    return text.replace("|", "\\|").replace("[", "\\[").replace("]", "\\]")


def _concept_page(
    concept_id: str,
    mentions: list[Mention],
    taxonomy: dict[str, dict],
    co_occurrence: dict[str, Counter],
    slug_for: dict[str, str],
    entries_cache: dict[Path, list[MindmapEntry]],
    corpus: Path,
) -> str:
    tax_entry = taxonomy.get(concept_id, {})
    label = tax_entry.get("preferred_label") or mentions[0].preferred_label
    aliases = tax_entry.get("aliases") or []
    domain = tax_entry.get("domain") or ""
    # video_id-normalized (issue #150 FIX10): a video mis-filed under two
    # channel-folder names must be counted once and rendered under exactly
    # one channel heading below - see `canonical_channel_by_video`.
    channel_by_video = canonical_channel_by_video(mentions)
    video_ids = sorted(channel_by_video)
    channels = sorted(set(channel_by_video.values()))

    lines = [
        "---",
        "type: concept",
        f"concept_id: {concept_id}",
        f"generator: {GENERATOR_NAME}",
        f"generator_version: {GENERATOR_VERSION!r}",
        f"generated_from: {corpus.name}",
        f"videos: {len(video_ids)}",
        f"channels: {len(channels)}",
        "---",
        "",
        f"# {label}",
        "",
        f"> {REGEN_NOTICE}",
        "",
        PROSE_TODO,
        f"> Write 2-3 paragraphs on {label}: what it is, why it recurs across "
        "creators, and a judgment on where it is heading.",
        "",
    ]
    if domain:
        lines += [f"Domain: `{domain}`", ""]
    if aliases:
        lines += ["## Aliases", ""]
        lines += [f"- {a}" for a in sorted(aliases)]
        lines.append("")

    lines += [f"## Member videos ({len(video_ids)} across {len(channels)} channels)", ""]
    # Grouped by CANONICAL channel, not each mention's raw `m.video.channel`
    # (issue #150 FIX10): a video mis-filed under two channel-folder names
    # would otherwise land in both groups and be listed under both headings.
    # `seen_videos` below still guards within a group in case of duplicate
    # Mention rows for the same video_id.
    by_channel: dict[str, list[Mention]] = {}
    for m in mentions:
        by_channel.setdefault(channel_by_video[m.video.video_id], []).append(m)
    for channel in sorted(by_channel):
        lines += [f"### {channel}", "", "| Date | Video | As mentioned |", "|---|---|---|"]
        rows = sorted(by_channel[channel], key=lambda m: (m.video.published, m.video.title, m.video.video_id))
        seen_videos: set[str] = set()
        for m in rows:
            if m.video.video_id in seen_videos:
                continue
            seen_videos.add(m.video.video_id)
            link = mention_link(m, entries_cache)
            date = m.video.published or "(date unknown)"
            claim = m.as_mentioned or m.branch or "-"
            title_cell = _escape_md_table_cell(m.video.title)
            claim_cell = _escape_md_table_cell(claim)
            lines.append(f"| {date} | [{title_cell}]({link}) | {claim_cell} |")
        lines.append("")

    related = co_occurrence.get(concept_id, Counter())
    related_ranked = sorted(
        ((cid, n) for cid, n in related.items() if cid in slug_for and cid != concept_id),
        key=lambda t: (-t[1], t[0]),
    )
    if related_ranked:
        lines += ["## Related concepts", ""]
        for cid, n in related_ranked:
            other_label = taxonomy.get(cid, {}).get("preferred_label") or cid
            plural = "s" if n != 1 else ""
            lines.append(f"- [[{slug_for[cid]}]] ({other_label}) - shares {n} video{plural} - {PROSE_INLINE}")
        lines.append("")

    return "\n".join(lines)


def _index(
    selected_ids: list[str],
    mentions_by_concept: dict[str, list[Mention]],
    taxonomy: dict[str, dict],
    slug_for: dict[str, str],
    corpus: Path,
) -> str:
    lines = [
        "---",
        "type: index",
        f"generator: {GENERATOR_NAME}",
        f"generator_version: {GENERATOR_VERSION!r}",
        f"generated_from: {corpus.name}",
        f"pages: {len(selected_ids)}",
        "---",
        "",
        "# Concept Atlas",
        "",
        f"> {REGEN_NOTICE}",
        "",
        PROSE_TODO,
        "> Write the MOC intro: what this atlas is, how to wander it, one line of context per link below.",
        "",
        f"## Top {len(selected_ids)} stable concepts",
        "",
    ]
    for i, cid in enumerate(selected_ids, start=1):
        mentions = mentions_by_concept[cid]
        # video_id-normalized (issue #150 FIX10), same helper and same
        # policy as `_concept_page` and `select_stable_concepts` - the MOC
        # count must agree with the concept page's own header.
        channel_by_video = canonical_channel_by_video(mentions)
        video_ids = set(channel_by_video)
        channels = set(channel_by_video.values())
        label = taxonomy.get(cid, {}).get("preferred_label") or mentions[0].preferred_label
        lines.append(
            f"{i}. [[{slug_for[cid]}]] - {label} - {len(video_ids)} videos across "
            f"{len(channels)} channels - {PROSE_INLINE}"
        )
    lines.append("")
    return "\n".join(lines)


def _assign_slugs(selected_ids: list[str]) -> dict[str, str]:
    """Deterministic slug per concept_id, disambiguating collisions with a
    numeric suffix (mirrors wiki_atlas's collision handling) so one page
    never silently overwrites another.

    `MOC_BASENAME` is seeded into `used` (issue #150 FIX7) so a concept_id
    that happens to slugify to the MOC's own filename gets pushed to a "-2"
    suffix instead of silently colliding with the index page.
    """
    slug_for: dict[str, str] = {}
    used: set[str] = {MOC_BASENAME}
    for cid in selected_ids:
        base = slug = slugify(cid)
        n = 2
        while slug in used:
            slug = f"{base}-{n}"
            n += 1
        used.add(slug)
        slug_for[cid] = slug
    return slug_for


def build_pages(
    corpus: Path,
    top_n: int = DEFAULT_TOP_N,
    min_channels: int = MIN_STABLE_CHANNELS,
) -> dict[str, str]:
    """Pure(ish) top-level renderer: corpus directory -> {relative path: markdown}.

    The only filesystem interaction is reading; nothing is written here.
    """
    records = collect_corpus_videos(corpus)
    mentions_by_concept = build_mentions(records)
    selected_ids = select_stable_concepts(mentions_by_concept, top_n=top_n, min_channels=min_channels)
    taxonomy = load_taxonomy(corpus)
    co_occurrence = build_co_occurrence(records, set(selected_ids))
    slug_for = _assign_slugs(selected_ids)
    entries_cache: dict[Path, list[MindmapEntry]] = {}

    pages: dict[str, str] = {}
    for cid in selected_ids:
        pages[f"{slug_for[cid]}.md"] = _concept_page(
            cid, mentions_by_concept[cid], taxonomy, co_occurrence, slug_for, entries_cache, corpus
        )
    pages[f"{MOC_BASENAME}.md"] = _index(selected_ids, mentions_by_concept, taxonomy, slug_for, corpus)
    return pages


def _frontmatter_generator(text: str) -> str | None:
    """Best-effort read of the `generator:` value from a page's frontmatter
    block (issue #150 FIX1c). Returns None when there is no frontmatter, no
    `generator:` key, or an empty value - a foreign page that predates any
    generator stamp is treated the same as "no signal", never as "safe to
    overwrite" or "ours"."""
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    for line in text[3:end].splitlines():
        line = line.strip()
        if line.startswith("generator:"):
            value = line.split(":", 1)[1].strip()
            return value or None
    return None


def write_pages(pages: dict[str, str], out_dir: Path) -> None:
    """Write every page under out_dir; refuses to write anywhere else.

    Two namespace-collision guards (issue #150 FIX1), both scoped to
    `out_dir` only - this generator never looks outside its own `--out`:

    - **Fail-closed ownership (issue #150 second review round, FIX9).** An
      existing file is overwritten ONLY when its frontmatter's `generator:`
      value is EXACTLY `GENERATOR_NAME`. Every other state - no frontmatter,
      empty or malformed frontmatter, a foreign generator's stamp, or a
      file that cannot be read at all - aborts the whole run (nothing is
      written) rather than falling through to an overwrite. The prior
      revision only refused when it could positively identify a *different*
      generator's stamp; an unreadable file or missing/malformed
      frontmatter fell through that check and was silently overwritten -
      exactly the failure `_frontmatter_generator`'s own docstring warns
      against, and the vector by which a same-named hand-authored note
      would be destroyed by a routine rerun.
    - **Own-stale pruning.** After writing, files already in `out_dir` that
      this SAME generator wrote in a prior run but that are absent from the
      current page set are deleted. Foreign files, and files with no
      readable `generator:` stamp at all, are never touched - pruning only
      ever removes pages this generator is sure it owns. This half was
      already fail-closed (`== GENERATOR_NAME`, not `!=`) before this pass;
      it is unchanged here.
    """
    root = out_dir.resolve()
    root.mkdir(parents=True, exist_ok=True)

    resolved: dict[str, Path] = {}
    for rel in pages:
        path = (root / rel).resolve()
        if root not in (path, *path.parents):
            raise ValueError(f"page path escapes output dir: {rel}")
        if path.exists():
            # Deliberately not `_read_text_best_effort`: that helper feeds
            # the corpus-walk skip counter (`skipped_file_count`), and an
            # unreadable OUTPUT page is a different signal than a corpus
            # artifact - the two must not be conflated in one count.
            try:
                existing_text = path.read_text(encoding="utf-8")
            except OSError as exc:
                raise SystemExit(
                    f"refusing to overwrite {path}: could not read it to verify "
                    f"ownership ({exc}). Move the file aside or point --out at a "
                    "different directory."
                ) from exc
            owner = _frontmatter_generator(existing_text)
            if owner != GENERATOR_NAME:
                reason = (
                    f"generated by '{owner}'"
                    if owner
                    else "not stamped by any generator (missing, empty, or malformed frontmatter)"
                )
                raise SystemExit(
                    f"refusing to overwrite {path}: it is {reason}, not {GENERATOR_NAME}. "
                    "Move the file aside, or point --out at a directory not shared with "
                    "another generator's pages or hand-authored notes."
                )
        resolved[rel] = path

    for rel, path in resolved.items():
        path.write_text(pages[rel], encoding="utf-8")

    current_names = set(pages)
    for existing_path in sorted(root.glob("*.md")):
        if existing_path.name in current_names:
            continue
        try:
            text = existing_path.read_text(encoding="utf-8")
        except OSError:
            continue
        if _frontmatter_generator(text) == GENERATOR_NAME:
            existing_path.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate top-N stable-concept wiki pages from a video-intel corpus (issue #148)."
    )
    parser.add_argument("--corpus", type=Path, required=True, help="Path to the corpus (output_dir), read-only")
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Output folder for the generated pages (default: <corpus>/_wiki/concept-pages)",
    )
    parser.add_argument(
        "--top",
        type=int,
        default=DEFAULT_TOP_N,
        help=f"Number of stable concepts to render, must be >= 1 (default {DEFAULT_TOP_N})",
    )
    args = parser.parse_args()

    if args.top < 1:
        parser.error(f"--top must be >= 1 (got {args.top})")

    corpus = args.corpus.resolve()
    if not corpus.is_dir():
        sys.exit(f"corpus not found: {corpus}")
    out_dir = (args.out.resolve()) if args.out else (corpus / "_wiki" / "concept-pages")

    pages = build_pages(corpus, top_n=args.top)
    write_pages(pages, out_dir)
    concept_pages = len(pages) - 1  # everything but the MOC page
    skipped = skipped_file_count()
    print(
        f"wrote {len(pages)} pages to {out_dir} ({concept_pages} concept pages + MOC, "
        f"top {args.top} requested, {skipped} corpus files skipped as unreadable/unparseable)"
    )


if __name__ == "__main__":
    main()

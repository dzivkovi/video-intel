"""The committed demo bundle (`examples/catalog/`) stays what the exporter would write.

The guardrail says the bundle is regenerated by `atlas_export.py`, never edited by
hand, and carries public data only. These tests make that claim mechanical: every row
satisfies the committed policy and the public field list, the page re-renders
byte-identical from the JSON beside it, and (when the owner's private term list is
present on this machine) no term appears in any committed byte.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))

import atlas_export as ax
import atlas_render as ar

DEMO = Path(__file__).resolve().parent.parent / "examples" / "catalog"
PRIVATE_TERMS = Path.home() / ".claude" / "guardrail-terms.txt"


@pytest.fixture(scope="module")
def bundle():
    atlas = json.loads((DEMO / "atlas.json").read_text(encoding="utf-8"))
    policy = ax.load_policy(DEMO / "export-policy.yaml")
    return atlas, policy


def test_the_bundle_is_an_export_whose_rows_obey_the_committed_policy(bundle):
    atlas, policy = bundle
    assert atlas["generator"] == ax.GENERATOR_NAME
    assert atlas["export"]["channels"] == sorted(policy["channels"])
    assert atlas["export"]["since"] == policy["since"]
    assert atlas["export"]["policy_sha256_16"] == ax.policy_fingerprint(DEMO / "export-policy.yaml")
    assert "source_rows" not in atlas["export"]
    allowed, excluded = set(policy["channels"]), set(policy["exclude_video_ids"])
    for r in atlas["rows"]:
        assert tuple(r) == ax.PUBLIC_ROW_KEYS
        assert r["channel"] in allowed and r["video_id"] not in excluded
        assert policy["since"] is None or r["published"] >= policy["since"]
        assert ax.canonical_url(r) == r["url"]
        for dl in r["deep_links"]:
            assert dl["url"] == f"{r['url']}&t={dl['seconds']}"
    assert set(policy["channels"]) == {r["channel"] for r in atlas["rows"]}


def test_side_tables_are_rebuilt_from_the_rows(bundle):
    atlas, _ = bundle
    referenced = {c for r in atlas["rows"] for c in r["concept_ids"]}
    assert set(atlas["concepts"]) == referenced
    counts: dict[str, int] = {}
    for r in atlas["rows"]:
        counts[r["channel"]] = counts.get(r["channel"], 0) + 1
    assert atlas["summary"] == {
        "channels": dict(sorted(counts.items())),
        "topics": {},
        "unthreaded": 0,
        "rows": len(atlas["rows"]),
    }


def test_the_page_re_renders_byte_identical_from_the_json_beside_it(bundle):
    atlas, _ = bundle
    template = ar.TEMPLATE_PATH.read_text(encoding="utf-8")
    expected = ar.render(atlas, template)
    assert (DEMO / "catalog.html").read_text(encoding="utf-8") == expected


def test_no_private_term_is_in_any_committed_byte():
    if not PRIVATE_TERMS.exists():
        pytest.skip("the owner's private term list is not on this machine")
    terms, _ = ax.load_deny_terms(PRIVATE_TERMS)
    for name in ("atlas.json", "catalog.html", "export-policy.yaml"):
        assert ax.deny_term_hits((DEMO / name).read_bytes(), terms) == [], name
